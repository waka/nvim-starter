  vim.cmd([[cnoreabbrev <expr> terminal getcmdtype() == ':' && getcmdline() == 'terminal' ? 'botright 15split \| terminal' : 'terminal']])

  -- NOTE: You can add your own plugins, configuration, etc. in `lua/custom/plugins/*.lua`.
  require 'custom.plugins'

  -- Tab as project
  vim.pack.add { gh 'tiagovla/scope.nvim' }
  require('scope').setup {}

  -- Search directories
  local project_roots = {
    'C:/Users/ywaka',
  }

  local function open_project(dir)
    vim.cmd 'tabnew'
    vim.cmd('tcd ' .. vim.fn.fnameescape(dir))
  end

  local function pick_project()
    local pickers = require 'telescope.pickers'
    local finders = require 'telescope.finders'
    local conf = require('telescope.config').values
    local actions = require 'telescope.actions'
    local action_state = require 'telescope.actions.state'

    local cmd = { 'fd', '--type', 'd', '--max-depth', '2', '.' }
    vim.list_extend(cmd, project_roots)

    pickers.new({}, {
      prompt_title = 'Open Project',
      finder = finders.new_oneshot_job(cmd, {}),
      sorter = conf.generic_sorter {},
      attach_mappings = function(bufnr)
        actions.select_default:replace(function()
          local entry = action_state.get_selected_entry()
          actions.close(bufnr)
          if entry then open_project(entry[1]) end
        end)
        return true
      end,
    }):find()
  end

  vim.api.nvim_create_user_command('Project', function(opts)
    if opts.args ~= '' then
      open_project(opts.args)
    else
      pick_project()
    end
  end, { nargs = '?', complete = 'dir' })

  vim.keymap.set('n', '<leader>sp', pick_project, { desc = '[S]earch [P]rojects' })

  -- Zonvie (Neovim GUI)
  vim.api.nvim_create_autocmd("UIEnter", {
    once = true,
    callback = function()
      if vim.g.zonvie_channel then
        vim.o.columns = 140
        vim.o.lines = 50
      end
    end,
  })
end

